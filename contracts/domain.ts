/** Contract v1.0.0 shared DTOs. See api.ts for implemented endpoint status. */
export type Id = string;
/** Safe integer MYR minor units. Financial entity amounts are positive unless stated. */
export type Sen = number;
/** Valid ISO 8601 UTC timestamp ending Z; date-only fields use the MYT calendar. */
export type UtcTimestamp = string;
export type MytDate = string;
export type Language = "en" | "ms" | "zh";
export type Role = "owner" | "finance" | "pm";
export type ProcessingStatus = "ready" | "needs_review" | "manual_required";

export interface TenantEntity {
  id: Id;
  companyId: Id;
  version: number;
  createdAt: UtcTimestamp;
  updatedAt: UtcTimestamp;
}

export interface Company {
  id: Id;
  name: string;
  currency: "MYR";
  timezone: "Asia/Kuala_Lumpur";
  /** Bank-ledger aggregate version; advances on import or allocation. */
  version: number;
}

export interface DemoUser {
  id: Id;
  displayName: string;
  companyId: Id;
  role: Role;
}

export interface Customer extends TenantEntity {
  name: string;
  /** Maintained independently of uploaded evidence; no automatic alias learning. */
  payerAliases: string[];
  preferredLanguage: Language;
}

export interface Project extends TenantEntity {
  customerId: Id;
  name: string;
  milestoneIds: Id[];
}

export interface Milestone extends TenantEntity {
  projectId: Id;
  customerId: Id;
  title: string;
  amountSen: Sen;
  dueDate: MytDate;
  status: "planned" | "completed";
  completedAt: UtcTimestamp | null;
  invoiceId: Id | null;
}

export type InvoiceStatus = "draft" | "issued" | "partially_paid" | "paid" | "rejected";
export interface Invoice extends TenantEntity {
  customerId: Id;
  projectId: Id;
  milestoneId: Id;
  /** Generated by the server, never supplied by the client. */
  number: string;
  currency: "MYR";
  totalAmountSen: Sen;
  paidAmountSen: Sen;
  outstandingAmountSen: Sen;
  dueDate: MytDate;
  status: InvoiceStatus;
  collectionStatus: "not_started" | "active" | "stopped";
  issuedAt: UtcTimestamp | null;
  approvedBy: Id | null;
  confirmedPromiseId: Id | null;
}

export interface Reminder extends TenantEntity {
  invoiceId: Id;
  language: Language;
  draftText: string;
  status: "draft" | "sent_simulated";
  generationMode: "ai" | "fallback_template" | "manual";
  sentAt: UtcTimestamp | null;
  approvedBy: Id | null;
}

export type ReplyIntent = "paid" | "promise" | "partial" | "dispute" | "other";
export interface ExtractionReview {
  /** Routing signal in [0,1], not a calibrated statistical probability. */
  confidence: number | null;
  source: "ai" | "manual";
  /** Server-stamped and required for manual evidence. Client cannot set these. */
  reviewedBy: Id | null;
  reviewedAt: UtcTimestamp | null;
}

export interface ReplyExtraction extends ExtractionReview {
  intent: ReplyIntent;
  promisedDate: MytDate | null;
  amountSen: Sen | null;
}

export interface Reply extends TenantEntity {
  invoiceId: Id;
  text: string;
  receivedAt: UtcTimestamp;
  language: Language;
  receiptId: Id | null;
  processingStatus: ProcessingStatus;
  extraction: ReplyExtraction | null;
  confirmedPromiseId: Id | null;
}

export interface ReceiptEvidence extends ExtractionReview {
  /** May be the sender's bank; do not equate with the receiving account bank. */
  bank: string | null;
  amountSen: Sen | null;
  reference: string | null;
  transferredAt: UtcTimestamp | null;
  payer: string | null;
}

export interface Receipt extends TenantEntity {
  invoiceId: Id;
  replyId: Id | null;
  imageId: Id;
  imageSha256: string;
  mimeType: "image/png" | "image/jpeg" | "image/webp";
  byteLength: number;
  width: number;
  height: number;
  processingStatus: ProcessingStatus;
  evidence: ReceiptEvidence | null;
}

export interface BankCredit extends TenantEntity {
  externalId: string;
  /** Bank posting date in MYT, not a UTC midnight. */
  postedDate: MytDate;
  amountSen: Sen;
  reference: string;
  payer: string;
  /** Receiving account's bank. */
  bank: string;
  allocatedPaymentId: Id | null;
}

export type MatchVerdict =
  | "confirmed" | "partial" | "amount_mismatch"
  | "not_in_bank_yet" | "duplicate" | "needs_review";

export type MatchReason =
  | "exact_match" | "partial_amount" | "amount_differs"
  | "no_bank_reference" | "duplicate_image" | "reused_reference"
  | "credit_already_allocated" | "missing_field" | "invalid_evidence"
  | "low_confidence" | "manual_review_required" | "wrong_payer"
  | "multiple_candidates" | "date_outside_window" | "overpayment"
  | "invoice_not_collectible" | "future_transfer_time" | "future_bank_posting";

export interface MatchResult extends TenantEntity {
  invoiceId: Id;
  receiptId: Id;
  invoiceVersion: number;
  receiptVersion: number;
  bankLedgerVersion: number;
  eligibleCreditVersion: number | null;
  verdict: MatchVerdict;
  reasons: MatchReason[];
  candidateCreditIds: Id[];
  eligibleCreditId: Id | null;
  proposedPaymentAmountSen: Sen | null;
  proposedOutstandingAmountSen: Sen | null;
  checkedAt: UtcTimestamp;
  status: "pending" | "applied";
}

export interface Payment extends TenantEntity {
  invoiceId: Id;
  bankCreditId: Id;
  receiptId: Id;
  matchResultId: Id;
  amountSen: Sen;
  /** MYT date of Finance confirmation: demo-ledger recognition date. */
  effectiveDate: MytDate;
  /** Original bank evidence date; no backdated demo-ledger mutation. */
  bankPostedDate: MytDate;
  confirmedAt: UtcTimestamp;
  confirmedBy: Id;
}

export interface PaymentPromise extends TenantEntity {
  invoiceId: Id;
  replyId: Id;
  promisedDate: MytDate;
  /** Whole outstanding amount at confirmation; later receipts reduce expected remainder. */
  amountSen: Sen;
  status: "active" | "superseded" | "fulfilled";
  confirmedBy: Id;
  confirmedAt: UtcTimestamp;
}

export interface Expense extends TenantEntity {
  title: string;
  amountSen: Sen;
  dueDate: MytDate;
}

export interface ActivityEvent {
  id: Id;
  companyId: Id;
  actorId: Id;
  action: string;
  entityType: string;
  entityId: Id;
  occurredAt: UtcTimestamp;
  outcome: "succeeded" | "rejected";
  reasonCode: string | null;
  requestId: string;
  /** Human-readable audit summary without secrets or raw external-model prompts. */
  summary: string;
}

/** Deterministic matcher input; evaluation may call this shape without HTTP. */
export interface MatcherInput {
  asOf: UtcTimestamp;
  companyId: Id;
  bankLedgerVersion: number;
  invoice: Invoice;
  customer: Customer;
  receipt: Receipt;
  bankCredits: BankCredit[];
  existingReceipts: Receipt[];
  payments: Payment[];
}

export interface ForecastDefaults {
  asOfDate: MytDate;
  /** MYT opening balance, already including payments confirmed before that day. */
  openingBalanceSen: Sen;
  safetyThresholdSen: Sen;
  delayDays: number;
}

export interface ForecastInput extends ForecastDefaults {
  asOf: UtcTimestamp;
  companyId: Id;
  invoices: Invoice[];
  promises: PaymentPromise[];
  payments: Payment[];
  expenses: Expense[];
}

export interface ForecastEntry {
  id: Id;
  date: MytDate;
  kind: "actual_payment" | "expected_receipt" | "expense";
  /** Signed cash delta: expense negative, receipt positive. */
  amountSen: Sen;
  sourceId: Id;
  invoiceId: Id | null;
}

export interface ForecastDay {
  date: MytDate;
  openingBalanceSen: Sen;
  actualReceiptsSen: Sen;
  expectedReceiptsSen: Sen;
  expensesSen: Sen;
  closingBalanceSen: Sen;
  belowSafetyThreshold: boolean;
  entryIds: Id[];
}

export interface ForecastScenario {
  kind: "on_time" | "delayed";
  delayDays: number;
  entries: ForecastEntry[];
  days: ForecastDay[];
  /** Expected receipt source IDs shifted beyond the 30-day horizon. */
  deferredInvoiceIds: Id[];
}

export interface Forecast {
  companyId: Id;
  asOf: UtcTimestamp;
  asOfDate: MytDate;
  timezone: "Asia/Kuala_Lumpur";
  horizonDays: 30;
  openingBalanceSen: Sen;
  safetyThresholdSen: Sen;
  scenarios: [ForecastScenario, ForecastScenario];
}

/** Only these fields may reach an external model; all values must be sanitized. */
export interface AiInput {
  task: "draft_reminder" | "extract_reply" | "structure_receipt";
  redactedText: string;
  language: Language;
  outstandingAmountSen?: Sen;
  replyReceivedAt?: UtcTimestamp;
  referenceDate?: MytDate;
  timezone: "Asia/Kuala_Lumpur";
}

export interface AiReplyOutput {
  intent: ReplyIntent;
  promisedDate: MytDate | null;
  amountSen: Sen | null;
  confidence: number;
}

export interface AiReceiptOutput {
  bank: string | null;
  amountSen: Sen | null;
  /** Must be a token already present in redactedText; resolve locally. */
  referenceToken: string | null;
  transferredAt: UtcTimestamp | null;
  payerToken: string | null;
  confidence: number;
}

export interface AiReminderOutput {
  draftText: string;
  language: Language;
}
